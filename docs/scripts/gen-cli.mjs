// Writes one docs page per `tachyon` command, holding that command's exact --help text.
// Usage: node gen-cli.mjs <path-to-tachyon-binary> <outDir>
// Walks the "Commands:" list of every help text, so new subcommands get pages without edits here.
// Pages are named tachyon[-sub...].md; any other tachyon*.md in outDir is stale and removed.
import { execFileSync } from 'node:child_process';
import { mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const [bin, outDir] = process.argv.slice(2);
if (!bin || !outDir) {
  console.error('usage: node gen-cli.mjs <path-to-tachyon-binary> <outDir>');
  process.exit(2);
}

// A line or two above the help text, for the commands where it helps to know where to read on.
const intros = {
  tachyon:
    '`--config` works on every command, before or after the subcommand. Every setting in the file can also come from a `TACHYON_*` environment variable: see the [configuration reference](/reference/config).',
  'tachyon serve': 'The Docker image runs this command by default. Its settings are in [Configuration](/configuration).',
  'tachyon migrate': '`serve` runs the same migrations on startup, so you only need this to migrate without serving.',
  'tachyon schema': 'How to keep schemas in Git and move them between environments is in [Schema files](/schema-files).',
  'tachyon schema export': 'See [Schema files: Export](/schema-files#export).',
  'tachyon schema diff': 'See [Schema files: Compare with `diff`](/schema-files#compare-with-diff).',
  'tachyon schema apply': 'See [Schema files: Apply](/schema-files#apply).',
};

// Subcommand names from the "Commands:" section, minus clap's built-in `help`. A command line is
// indented exactly two spaces; wrapped description lines are indented further, so they never match.
const subcommands = (help) => {
  const section = help.split(/^Commands:\n/m)[1];
  if (!section) return [];
  return section
    .split(/\n(?!\s)/)[0]
    .split('\n')
    .map((line) => line.match(/^  (\S+)(?:\s{2,}|$)/)?.[1])
    .filter((name) => name && name !== 'help');
};

// Every --help runs before any file is touched, so a failing binary leaves the pages as they were.
const pages = [];
const walk = (path) => {
  const help = execFileSync(bin, [...path, '--help'], { encoding: 'utf8' })
    .split('\n')
    .map((line) => line.trimEnd())
    .join('\n')
    .trimEnd();
  pages.push({ path, help });
  for (const sub of subcommands(help)) walk([...path, sub]);
};
walk([]);

mkdirSync(outDir, { recursive: true });
for (const file of readdirSync(outDir)) if (/^tachyon(-.+)?\.md$/.test(file)) rmSync(join(outDir, file));

pages.forEach(({ path, help }, order) => {
  const command = ['tachyon', ...path].join(' ');
  if (!intros[command]) console.warn(`gen-cli: no intro for \`${command}\`; add one to intros in gen-cli.mjs`);
  const intro = intros[command] ? `${intros[command]}\n\n` : '';
  writeFileSync(
    join(outDir, `${['tachyon', ...path].join('-')}.md`),
    `---
# Generated by docs/scripts/gen-cli.mjs from the tachyon binary. Edit the script, not this file.
title: ${JSON.stringify(command)}
description: ${JSON.stringify(help.split('\n')[0])}
sidebar:
  order: ${order + 1}
---

${intro}\`\`\`text
${help}
\`\`\`
`,
  );
});
